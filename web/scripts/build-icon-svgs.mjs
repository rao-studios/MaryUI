/**
 * Emit every mark as a standalone .svg under design/icons/, for Sketch.
 *
 * Sketch's own SVG importer turns these into fully editable vectors on drag-in,
 * which is why there is no shapePath emitter here: its curve model needs
 * normalized frame coordinates, per-point curve modes, true cubic bounding
 * boxes and arc-to-bezier decomposition, and the importer already does all of
 * that correctly.
 *
 * Colours resolve to literals because Sketch has no CSS variables — but every
 * layer is NAMED after the token it came from, so the file can be re-bound to
 * the Color Variables liquid-platinum.sketch already ships.
 *
 * Two passes are deliberately left out: the brushed grain, which would import
 * as a rasterised noise fill rather than the pattern Sketch should apply
 * itself, and the contact shadow, which belongs on the Sketch layer as a real
 * shadow. Both are documented in design/README.md.
 */

import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { GLYPH_STROKE, VIEWBOX, glyphSvg, glyphs, objectNames, objectSvg, objects } from './icon-svg-lib.mjs'

const OUT = fileURLToPath(new URL('../design/icons/', import.meta.url))
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
/** Sketch names a layer from its id, which must be an XML name — no spaces. */
const slug = (s) => s.replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '')

rmSync(OUT, { recursive: true, force: true })
mkdirSync(new URL('glyph/', `file://${OUT}`), { recursive: true })
mkdirSync(new URL('object/', `file://${OUT}`), { recursive: true })

let g = 0
for (const [name, paths] of Object.entries(glyphs)) {
  writeFileSync(`${OUT}glyph/${name}.svg`, glyphSvg(name, paths))
  g++
}
let o = 0
for (const name of objectNames) {
  writeFileSync(`${OUT}object/${name}.svg`, objectSvg(name, objects[name]))
  o++
}

writeFileSync(
  `${OUT}README.md`,
  `# design/icons/\n\nGenerated by \`npm run icons\` — do not hand-edit; edit \`src/components/Icon/icons.json\`,\n` +
    `\`src/components/ObjectIcon/objects.json\` or the \`object\` group in \`tokens/tokens.json\`.\n\n` +
    `- \`glyph/\` — ${g} control marks, 24 grid, stroked at ${GLYPH_STROKE}px\n` +
    `- \`object/\` — ${o} lit objects, ${VIEWBOX} grid\n\n` +
    `Drag one into Sketch and its importer converts it to editable vectors. Every layer is named after\n` +
    `the token its colour came from (\`back · folder/top\`, \`keyline · edge/hairline\`), so the shapes can\n` +
    `be re-bound to the Color Variables \`liquid-platinum.sketch\` already ships.\n\n` +
    `Two passes are deliberately absent. The **brushed grain** would import as a rasterised noise fill\n` +
    `rather than the pattern Sketch should apply itself, and the **contact shadow** belongs on the layer\n` +
    `as a real Sketch shadow. Apply both in Sketch; the Icons artboard in \`liquid-platinum.sketch\` shows\n` +
    `what they look like in the running app.\n`,
)

console.log(`icons: ${g} glyphs + ${o} objects → design/icons/`)
